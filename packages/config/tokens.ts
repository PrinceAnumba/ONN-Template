import { clampChroma, converter, formatHex, interpolate, wcagContrast } from "culori";
import type { CountryConfig } from "./schema";

const toOklch = converter("oklch");

export const MIN_TEXT_CONTRAST = 4.5;
const LIGHTNESS_STEP = 0.005;

const CATEGORICAL = [
  "#0072B2",
  "#E69F00",
  "#009E73",
  "#CC79A7",
  "#56B4E9",
  "#D55E00",
  "#F0E442",
  "#000000",
];
const SURFACE_2 = "#F5F7FA";

/** Darkens a colour in OKLCH until it reaches 4.5:1 on white. */
export function deriveInk(color: string): { ink: string; adjusted: boolean } {
  const start = toOklch(color);
  if (!start) throw new Error(`Invalid colour: ${color}`);
  if (wcagContrast(color, "#FFFFFF") >= MIN_TEXT_CONTRAST) {
    return { ink: color.toUpperCase(), adjusted: false };
  }
  for (let l = start.l; l > 0; l -= LIGHTNESS_STEP) {
    const candidate = formatHex(clampChroma({ ...start, l }, "oklch"));
    if (wcagContrast(candidate, "#FFFFFF") >= MIN_TEXT_CONTRAST) {
      return { ink: candidate.toUpperCase(), adjusted: true };
    }
  }
  return { ink: "#000000", adjusted: true };
}

/** Five map classes from `--onn-surface-2` to the primary ink, interpolated in OKLCH. */
export function sequentialScale(ink: string): string[] {
  const scale = interpolate([SURFACE_2, ink], "oklch");
  return [0, 0.25, 0.5, 0.75, 1].map((t) => formatHex(scale(t)).toUpperCase());
}

export function renderTokensCss(brand: CountryConfig["brand"]): {
  css: string;
  inkAdjusted: boolean;
  ink: string;
} {
  const { ink, adjusted } = deriveInk(brand.primary);
  const lines = [
    `--onn-primary: ${brand.primary};`,
    `--onn-primary-ink: ${ink};`,
    `--onn-secondary: ${brand.secondary};`,
    `--onn-accent: ${brand.accent};`,
    `--onn-ink: ${brand.neutralDark};`,
    "--onn-muted: #5B6472;",
    "--onn-line: #DDE2E8;",
    "--onn-surface: #FFFFFF;",
    `--onn-surface-2: ${SURFACE_2};`,
    "--onn-positive: #1A7F37;",
    "--onn-negative: #C62828;",
    "--onn-at-risk: #B26A00;",
    "--onn-compare: #8A94A6;",
    `--onn-peer-band: color-mix(in srgb, ${brand.primary} 12%, transparent);`,
    `--onn-focus: 0 0 0 2px #fff, 0 0 0 4px ${ink};`,
    "--onn-radius-card: 8px;",
    "--onn-radius-input: 6px;",
    "--onn-radius-pill: 999px;",
    "--onn-shadow-1: 0 1px 2px rgb(15 28 46 / .06), 0 2px 8px rgb(15 28 46 / .06);",
    "--onn-shadow-2: 0 8px 28px -8px rgb(15 28 46 / .22);",
    "--onn-ease: cubic-bezier(.2, .8, .2, 1);",
    "--onn-dur-1: 120ms;",
    "--onn-dur-2: 220ms;",
    "--onn-dur-3: 360ms;",
    ...[4, 8, 12, 16, 24, 32, 48, 64].map((px, i) => `--s-${i + 1}: ${px}px;`),
    ...CATEGORICAL.map((color, i) => `--onn-cat-${i + 1}: ${color};`),
    ...sequentialScale(ink).map((color, i) => `--onn-seq-${i + 1}: ${color};`),
  ];
  const css = [
    "/* Generated by packages/config/generate.ts. Do not edit. */",
    ":root {",
    "  color-scheme: light;",
    ...lines.map((line) => `  ${line}`),
    "}",
    "",
  ].join("\n");
  return { css, inkAdjusted: adjusted, ink };
}
