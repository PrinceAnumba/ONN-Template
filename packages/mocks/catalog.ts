export interface IndicatorSeed {
  code: string;
  pillar: string;
  theme: string;
  name: L;
  shortDefinition: L;
  unit: string;
  periodicity: Periodicity;
  geoLevels: string[];
  disaggregations: string[];
  higherIsBetter: boolean;
  isHeadline: boolean;
  start: number;
  end: number;
  max?: number;
  method: SourceMethod;
  status: IndicatorStatus;
  itu?: string;
  synonyms: string[];
  countVariant: boolean;
}

interface RowOptions {
  period?: Periodicity;
  geo?: Geo;
  dims?: string;
  lowerBetter?: boolean;
  headline?: boolean;
  method?: SourceMethod;
  status?: IndicatorStatus;
  itu?: string;
  synonyms?: string[];
  countVariant?: boolean;
}

function row(
  code: string,
  theme: string,
  fr: string,
  en: string,
  defFr: string,
  defEn: string,
  unit: string,
  start: number,
  end: number,
  options: RowOptions = {},
): IndicatorSeed {
  const pillar = code.split(".")[0] as string;
  return {
    code,
    pillar,
    theme,
    name: { fr, en },
    shortDefinition: { fr: defFr, en: defEn },
    unit,
    periodicity: options.period ?? "annual",
    geoLevels: GEO[options.geo ?? "n"],
    disaggregations: DIMS[options.dims ?? ""] ?? [],
    higherIsBetter: !options.lowerBetter,
    isHeadline: options.headline ?? false,
    start,
    end,
    max: unit === "pct" ? 100 : undefined,
    method: options.method ?? "administrative",
    status: options.status ?? "published",
    itu: options.itu,
    synonyms: options.synonyms ?? [],
    countVariant: options.countVariant ?? false,
  };
}

